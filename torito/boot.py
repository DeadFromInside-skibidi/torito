"""
torito.boot — Bootloader Configuration Synthesizer
====================================================
Generates standard bootloader configuration scripts and files for
UEFI (GRUB2, Limine, systemd-boot, EFI Shell startup.nsh) and BIOS
(ISOLINUX / SYSLINUX, Limine BIOS) directly into the VFS, EFI ESP,
and ISO9660 filesystem layouts without requiring host tools.
"""

from __future__ import annotations

from typing import Dict, Optional
from .config import BuildConfig


def generate_grub_cfg(config: BuildConfig) -> str:
    """
    Generate a standard GRUB 2 configuration file (grub.cfg)
    supporting both BIOS and UEFI live boot.
    """
    cmdline = config.kernel.cmdline
    title = f"{config.name} {config.version} ({config.arch}) Live"

    return f"""# GRUB2 Configuration generated by Torito ISO Compiler
set default="0"
set timeout=5

function load_video {{
    if [ x$feature_all_video_module = xy ]; then
        insmod all_video
    else
        insmod efi_gop
        insmod efi_uga
        insmod video_bochs
        insmod video_cirrus
    fi
}}

load_video
insmod font

if loadfont /boot/grub/fonts/unicode.pf2 ; then
    set gfxmode=auto
    insmod gfxterm
    set locale_dir=/boot/grub/locale
    set lang=en_US
    terminal_output gfxterm
fi

insmod part_gpt
insmod part_msdos
insmod iso9660
insmod fat

menuentry "{title}" --class gnu-linux --class gnu --class os {{
    linux /boot/vmlinuz {cmdline}
    initrd /boot/initramfs.img
}}

menuentry "{title} (Safe Graphics / Fallback)" --class gnu-linux --class gnu --class os {{
    linux /boot/vmlinuz {cmdline} nomodeset
    initrd /boot/initramfs.img
}}

menuentry "Reboot" {{
    reboot
}}

menuentry "Poweroff" {{
    halt
}}
"""


def generate_limine_cfg(config: BuildConfig) -> str:
    """
    Generate a modern Limine bootloader configuration file (limine.cfg)
    supporting BIOS, UEFI 32/64-bit, and direct kernel boot.
    """
    cmdline = config.kernel.cmdline
    title = f"{config.name} {config.version}"

    return f"""# Limine Bootloader Configuration generated by Torito ISO Compiler
TIMEOUT=5
DEFAULT_ENTRY=1

: {title}
    PROTOCOL=linux
    KERNEL_PATH=boot:///boot/vmlinuz
    CMDLINE={cmdline}
    MODULE_PATH=boot:///boot/initramfs.img

: {title} (nomodeset)
    PROTOCOL=linux
    KERNEL_PATH=boot:///boot/vmlinuz
    CMDLINE={cmdline} nomodeset
    MODULE_PATH=boot:///boot/initramfs.img
"""


def generate_isolinux_cfg(config: BuildConfig) -> str:
    """
    Generate a Syslinux / ISOLINUX configuration file (isolinux.cfg)
    for classic El Torito BIOS boot.
    """
    cmdline = config.kernel.cmdline
    title = f"{config.name} {config.version}"

    return f"""# ISOLINUX Configuration generated by Torito ISO Compiler
DEFAULT live
TIMEOUT 50
PROMPT 1

LABEL live
    MENU LABEL {title}
    LINUX /boot/vmlinuz
    INITRD /boot/initramfs.img
    APPEND {cmdline}

LABEL live-safe
    MENU LABEL {title} (Safe Graphics)
    LINUX /boot/vmlinuz
    INITRD /boot/initramfs.img
    APPEND {cmdline} nomodeset
"""


def generate_startup_nsh(config: BuildConfig) -> str:
    """
    Generate an EFI Shell startup.nsh batch script allowing UEFI fallback
    direct kernel boot via the Linux EFI Stub loader.
    """
    cmdline = config.kernel.cmdline
    return f"""@echo -off
echo Booting {config.name}...
vmlinuz initrd=\\initramfs.img {cmdline}
"""


def generate_systemd_boot_entries(config: BuildConfig) -> Dict[str, str]:
    """
    Generate systemd-boot loader configuration and entry files.
    """
    cmdline = config.kernel.cmdline
    loader_conf = """# loader.conf generated by Torito
default torito.conf
timeout 5
console-mode max
editor no
"""
    entry_conf = f"""# torito.conf
title   {config.name} {config.version}
linux   /vmlinuz
initrd  /initramfs.img
options {cmdline}
"""
    return {
        "/loader/loader.conf": loader_conf,
        "/loader/entries/torito.conf": entry_conf,
    }

