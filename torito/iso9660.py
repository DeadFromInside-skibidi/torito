GPT_PARTITION_ARRAY_SIZE: int = GPT_NUM_PARTITION_ENTRIES * GPT_PARTITION_ENTRY_SIZE  # 16,384 bytes
GPT_PARTITION_ARRAY_LBAS: int = GPT_PARTITION_ARRAY_SIZE // LBA_SIZE  # 32 LBAs


