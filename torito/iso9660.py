class Iso9660Error(Exception):
    """Base exception for all ISO9660 assembler errors."""
    pass


class Iso9660PathError(Iso9660Error):
    """Raised when an invalid ISO9660 path or identifier is encountered."""
    pass


class Iso9660BuildError(Iso9660Error):
    """Raised when an ISO image cannot be built or validation fails."""
    pass


# ---------------------------------------------------------------------------
# Internal Helpers
# ---------------------------------------------------------------------------

def _clean_iso_string(text: str, max_length: int, pad_char: bytes = b" ") -> bytes:
    """
    Sanitise and pad an ASCII string for ISO9660 fixed-width descriptor fields.
    """
    cleaned = text.encode("ascii", errors="replace")[:max_length]
    return cleaned.ljust(max_length, pad_char)


