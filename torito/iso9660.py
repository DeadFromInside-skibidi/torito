def build_hybrid_iso(
    files: Dict[str, bytes],
    bios_boot_image: bytes = b"",
    efi_boot_image: bytes = b"",
    volume_id: str = "TORITO",
    system_id: str = "LINUX",
    publisher_id: str = "",
    application_id: str = "",
) -> bytes:
    """
    Assemble a complete bootable hybrid ISO9660 image from a dictionary of files.

    Parameters
    ----------
    files : Dict[str, bytes]
        Map of virtual file paths to their byte contents (e.g., ``{"/README": b"..."}``).
    bios_boot_image : bytes
        Optional BIOS El Torito boot image payload.
    efi_boot_image : bytes
        Optional UEFI FAT filesystem image (efiboot.img).
    volume_id : str
        Volume identifier.
    system_id : str
        System identifier.
    publisher_id : str
        Publisher identifier.
    application_id : str
        Application identifier.

    Returns
    -------
    bytes
        Complete, sector-aligned hybrid ISO9660 image.
    """
    builder = Iso9660Builder(
        volume_id=volume_id,
        system_id=system_id,
        publisher_id=publisher_id if publisher_id else "TORITO",
        application_id=application_id if application_id else "TORITO",
    )
    for path, data in files.items():
        builder.add_file(path, data)

    if bios_boot_image or efi_boot_image:
        builder.set_boot_images(
            bios_boot_image=bios_boot_image,
            efi_boot_image=efi_boot_image,
        )

    return builder.build()


def build_hybrid_iso_from_vfs(
    vfs: PosixVfs,
    bios_boot_image: bytes = b"",
    efi_boot_image: bytes = b"",
    volume_id: str = "TORITO",
    system_id: str = "LINUX",
    publisher_id: str = "",
    application_id: str = "",
) -> bytes:
    """
    Assemble a complete bootable hybrid ISO9660 image directly from a PosixVfs tree.
    """
    builder = Iso9660Builder(
        volume_id=volume_id,
        system_id=system_id,
        publisher_id=publisher_id if publisher_id else "TORITO",
        application_id=application_id if application_id else "TORITO",
    )
    builder.add_vfs(vfs)

    if bios_boot_image or efi_boot_image:
        builder.set_boot_images(
            bios_boot_image=bios_boot_image,
            efi_boot_image=efi_boot_image,
        )

    return builder.build()
