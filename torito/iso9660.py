# ---------------------------------------------------------------------------
# Main Iso9660Builder Class
# ---------------------------------------------------------------------------

class Iso9660Builder:
    """
    Pure-Python assembler for hybrid ISO9660 + El Torito + GPT disk images.

    Supports:
      - ISO9660 Level 1 / Level 2 directory records and Type L/M path tables.
      - El Torito boot catalog for BIOS (no-emulation) and UEFI.
      - Isohybrid Protective MBR at LBA 0.
      - Primary GPT at LBAs 1-33 (contained within the 32 KB System Area).
      - Backup GPT at image end.
    """

    def __init__(
        self,
        volume_id: str = "TORITO",
        system_id: str = "LINUX",
        publisher_id: str = "TORITO",
        application_id: str = "TORITO",
    ) -> None:
        """
        Initialise an ISO9660 builder instance.

        Parameters
        ----------
        volume_id : str
            ISO volume identifier (up to 32 ASCII characters).
        system_id : str
            System identifier (up to 32 ASCII characters).
        publisher_id : str
            Publisher identifier (up to 128 ASCII characters).
        application_id : str
            Application identifier (up to 128 ASCII characters).
        """
        self.volume_id: str = volume_id.strip() if volume_id else "TORITO"
        self.system_id: str = system_id.strip() if system_id else "LINUX"
        self.publisher_id: str = publisher_id.strip() if publisher_id else "TORITO"
        self.application_id: str = application_id.strip() if application_id else "TORITO"
        self.volume_set_id: str = self.volume_id
        self.data_preparer_id: str = self.publisher_id

        # Internal filesystem maps
        self._files: Dict[str, bytes] = {}
        self._file_mtimes: Dict[str, int] = {}
        self._directories: Set[str] = {"/"}
        self._dir_mtimes: Dict[str, int] = {}

        # Boot payload buffers
        self._bios_boot_image: bytes = b""
        self._efi_boot_image: bytes = b""

        # Deterministic timestamp: consult SOURCE_DATE_EPOCH if present
        epoch_env = os.environ.get("SOURCE_DATE_EPOCH")
        if epoch_env and epoch_env.isdigit():
            self._creation_time: int = int(epoch_env)
        else:
            self._creation_time = int(time.time())

    # ------------------------------------------------------------------
    # Filesystem Tree Population
    # ------------------------------------------------------------------

    def _normalise_path(self, path: str) -> str:
        """Canonicalise a path to a single leading slash POSIX string."""
        p = path.replace("\\", "/").strip()
        if not p.startswith("/"):
            p = "/" + p
        parts: List[str] = []
        for segment in p.split("/"):
            if not segment or segment == ".":
                continue
            if segment == "..":
                if parts:
                    parts.pop()
                continue
            parts.append(segment)
        return "/" + "/".join(parts) if parts else "/"

    def _ensure_ancestors(self, norm_path: str) -> None:
        """Ensure all parent directories of *norm_path* exist in the tree."""
        if norm_path == "/":
            self._directories.add("/")
            return
        parts = norm_path.strip("/").split("/")
        for i in range(1, len(parts)):
            ancestor = "/" + "/".join(parts[:i])
            self._directories.add(ancestor)

    def add_directory(self, iso_path: str, mtime: Optional[int] = None) -> None:
        """
        Add a directory to the ISO filesystem hierarchy.

        Parameters
        ----------
        iso_path : str
            Virtual directory path (e.g., ``/boot`` or ``/EFI/BOOT``).
        mtime : Optional[int]
            Unix timestamp for directory recording date.
        """
        norm = self._normalise_path(iso_path)
        self._directories.add(norm)
        self._ensure_ancestors(norm)
        if mtime is not None:
            self._dir_mtimes[norm] = mtime
        elif norm not in self._dir_mtimes:
            self._dir_mtimes[norm] = self._creation_time

    def add_file(self, iso_path: str, data: bytes, mtime: Optional[int] = None) -> None:
        """
        Add a regular file to the ISO filesystem hierarchy.

        Parameters
        ----------
        iso_path : str
            Virtual destination path (e.g., ``/boot/vmlinuz``).
        data : bytes
            Binary content of the file.
        mtime : Optional[int]
            Unix timestamp for file recording date.
        """
        if not isinstance(data, (bytes, bytearray)):
            raise TypeError(f"File data must be bytes or bytearray, got {type(data).__name__}")
        norm = self._normalise_path(iso_path)
        if norm == "/":
            raise Iso9660PathError("Cannot add a file at root path '/'")
        parent = str(PurePosixPath(norm).parent)
        self.add_directory(parent)
        self._files[norm] = bytes(data)
        self._file_mtimes[norm] = mtime if mtime is not None else self._creation_time

    def add_vfs(self, vfs: PosixVfs) -> None:
        """
        Ingest all directory nodes and regular files from a PosixVfs instance.
        """
        if hasattr(vfs, "_epoch") and vfs._epoch:
            self._creation_time = vfs._epoch

        for path, node in vfs.walk_sorted():
            if node.node_type == VfsNodeType.DIRECTORY:
                self.add_directory(path, mtime=node.mtime)
            elif node.node_type == VfsNodeType.REGULAR_FILE:
                self.add_file(path, node.data, mtime=node.mtime)
            elif node.node_type == VfsNodeType.SYMLINK:
                # Symlinks encoded as small text files containing target path
                self.add_file(path, node.link_target.encode("utf-8"), mtime=node.mtime)

    def set_boot_images(
        self,
        bios_boot_image: bytes = b"",
        efi_boot_image: bytes = b"",
    ) -> None:
        """
        Configure El Torito and UEFI boot image payloads.

        Parameters
        ----------
        bios_boot_image : bytes
            El Torito BIOS bootloader binary (e.g., isolinux.bin).
        efi_boot_image : bytes
            FAT filesystem image containing EFI/BOOT/BOOTX64.EFI (efiboot.img).
        """
        self._bios_boot_image = bytes(bios_boot_image) if bios_boot_image else b""
        self._efi_boot_image = bytes(efi_boot_image) if efi_boot_image else b""

    # ------------------------------------------------------------------
    # Binary Serialization Helpers
    # ------------------------------------------------------------------

    def _both_endian_32(self, val: int) -> bytes:
        """
        Pack an unsigned 32-bit integer in both little-endian and big-endian order (8 bytes total).
        """
        v = int(val) & 0xFFFFFFFF
        return struct.pack("<I", v) + struct.pack(">I", v)

    def _both_endian_16(self, val: int) -> bytes:
        """
        Pack an unsigned 16-bit integer in both little-endian and big-endian order (4 bytes total).
        """
        v = int(val) & 0xFFFF
        return struct.pack("<H", v) + struct.pack(">H", v)

    def _iso_datetime_17(self, timestamp: int) -> bytes:
        """
        Format a Unix timestamp as a 17-byte ISO 9660 ASCII recording timestamp.

        Structure (17 bytes):
          Bytes 0-3:   Year (4 ASCII digits)
          Bytes 4-5:   Month (2 ASCII digits: 01-12)
          Bytes 6-7:   Day (2 ASCII digits: 01-31)
          Bytes 8-9:   Hour (2 ASCII digits: 00-23)
          Bytes 10-11: Minute (2 ASCII digits: 00-59)
          Bytes 12-13: Second (2 ASCII digits: 00-59)
          Bytes 14-15: Hundredths of second (2 ASCII digits: 00-99)
          Byte 16:     GMT offset in 15-minute intervals (int8, 0 for GMT)
        """
        if timestamp <= 0:
            return b"0000000000000000\x00"
        gm = time.gmtime(timestamp)
        ascii_digits = (
            f"{gm.tm_year:04d}"
            f"{gm.tm_mon:02d}"
            f"{gm.tm_mday:02d}"
            f"{gm.tm_hour:02d}"
            f"{gm.tm_min:02d}"
            f"{gm.tm_sec:02d}"
            f"00"
        ).encode("ascii")
        return ascii_digits + struct.pack("b", 0)

    def _iso_datetime_7(self, timestamp: int) -> bytes:
        """
        Format a Unix timestamp as a 7-byte binary ISO 9660 directory recording date.

        Structure (7 bytes):
          Byte 0: uint8 years since 1900
          Byte 1: uint8 month (1-12)
          Byte 2: uint8 day of month (1-31)
          Byte 3: uint8 hour (0-23)
          Byte 4: uint8 minute (0-59)
          Byte 5: uint8 second (0-59)
          Byte 6: int8  GMT offset in 15-minute intervals (0 for GMT)
        """
        if timestamp <= 0:
            return struct.pack("BBBBBBb", 70, 1, 1, 0, 0, 0, 0)
        gm = time.gmtime(timestamp)
        years_since_1900 = max(0, min(255, gm.tm_year - 1900))
        return struct.pack(
            "BBBBBBb",
            years_since_1900,
            gm.tm_mon,
            gm.tm_mday,
            gm.tm_hour,
            gm.tm_min,
            gm.tm_sec,
            0,
        )

    def _iso_filename(self, name: str, is_dir: bool) -> bytes:
        """
        Convert a filename to an ISO9660 compliant identifier.

        - '.' maps to 0x00
        - '..' maps to 0x01
        - Directory names: uppercase [A-Z0-9_], no version suffix.
        - File names: uppercase [A-Z0-9_] with ';1' version suffix.
        """
        if name == ".":
            return b"\x00"
        if name == "..":
            return b"\x01"

        raw = name.strip()
        if is_dir:
            # Uppercase, replace non-compliant characters with underscore
            sanitised = re.sub(r"[^A-Z0-9_]", "_", raw.upper())
            sanitised = sanitised[:31] if sanitised else "DIR"
            return sanitised.encode("ascii")

        # Regular file: strip existing ';1' if already present
        if raw.endswith(";1"):
            raw = raw[:-2]

        if "." in raw:
            base, ext = raw.rsplit(".", 1)
        else:
            base, ext = raw, ""

        clean_base = re.sub(r"[^A-Z0-9_]", "_", base.upper())
        clean_ext = re.sub(r"[^A-Z0-9_]", "_", ext.upper())

        if not clean_base:
            clean_base = "FILE"

        clean_base = clean_base[:24]
        clean_ext = clean_ext[:6]

        if clean_ext:
            iso_name = f"{clean_base}.{clean_ext};1"
        else:
            iso_name = f"{clean_base};1"

        return iso_name.encode("ascii")

    # ------------------------------------------------------------------
    # Volume Descriptors & Record Builders
    # ------------------------------------------------------------------

    def _pad_str(self, val: str, length: int, pad_char: bytes = b" ") -> bytes:
        """Helper to format fixed-width ASCII fields."""
        return _clean_iso_string(val, length, pad_char)

    def _build_directory_record(
        self,
        name: str,
        sector: int,
        size: int,
        is_dir: bool,
        timestamp: Optional[int] = None,
    ) -> bytes:
        """
        Construct a single ISO 9660 directory record (minimum 34 bytes).

        Layout:
          0       1     Length of directory record
          1       1     Extended attribute record length (0)
          2       8     Location of extent: both-endian uint32
          10      8     Data length: both-endian uint32
          18      7     Recording date (7-byte binary)
          25      1     Flags: 0x02 = directory, 0x00 = file
          26      1     File unit size (0)
          27      1     Interleave gap size (0)
          28      4     Volume sequence number: both-endian uint16 = 1
          32      1     File identifier length (N)
          33      N     File identifier
          33+N    0-1   Padding to even record length
        """
        if timestamp is None:
            timestamp = self._creation_time

        ident_bytes = self._iso_filename(name, is_dir=is_dir)
        n = len(ident_bytes)
        raw_len = 33 + n
        pad_len = 1 if (raw_len % 2 != 0) else 0
        rec_len = raw_len + pad_len

        header = struct.pack("<BB", rec_len, 0)
        extent = self._both_endian_32(sector)
        data_len = self._both_endian_32(size)
        date_bytes = self._iso_datetime_7(timestamp)
        flags = 0x02 if is_dir else 0x00
        mid = struct.pack("<BBB", flags, 0, 0)
        vol_seq = self._both_endian_16(1)
        ident_hdr = struct.pack("<B", n)
        padding = b"\x00" * pad_len

        record = header + extent + data_len + date_bytes + mid + vol_seq + ident_hdr + ident_bytes + padding
        if len(record) != rec_len:
            raise Iso9660BuildError(f"Directory record length mismatch: expected {rec_len}, got {len(record)}")
        return record

    def _build_pvd(
        self,
        total_sectors: int,
        path_table_size: int,
        path_table_le_sector: int,
        path_table_be_sector: int,
        root_dir_record: bytes,
        timestamp: Optional[int] = None,
    ) -> bytes:
        """
        Construct the 2048-byte Primary Volume Descriptor (PVD) at sector 16.
        """
        if timestamp is None:
            timestamp = self._creation_time

        buf = bytearray(SECTOR_SIZE)
        buf[0] = ISO_VD_PRIMARY
        buf[1:6] = ISO_STANDARD_ID
        buf[6] = 1                         # Version: 1
        buf[7] = 0                         # Unused: 0
        buf[8:40] = self._pad_str(self.system_id, 32)
        buf[40:72] = self._pad_str(self.volume_id, 32)
        buf[72:80] = b"\x00" * 8           # Unused: zeros
        buf[80:88] = self._both_endian_32(total_sectors)
        buf[88:120] = b"\x00" * 32         # Unused: zeros
        buf[120:124] = self._both_endian_16(1)      # Volume Set Size = 1
        buf[124:128] = self._both_endian_16(1)      # Volume Sequence Number = 1
        buf[128:132] = self._both_endian_16(2048)   # Logical Block Size = 2048
        buf[132:140] = self._both_endian_32(path_table_size)
        buf[140:144] = struct.pack("<I", path_table_le_sector)
        buf[144:148] = struct.pack("<I", 0)         # Optional Type L
        buf[148:152] = struct.pack(">I", path_table_be_sector)
        buf[152:156] = struct.pack(">I", 0)         # Optional Type M

        if len(root_dir_record) != 34:
            raise Iso9660BuildError(
                f"PVD root directory record must be exactly 34 bytes, got {len(root_dir_record)}"
            )
        buf[156:190] = root_dir_record

        buf[190:318] = self._pad_str(self.volume_set_id, 128)
        buf[318:446] = self._pad_str(self.publisher_id, 128)
        buf[446:574] = self._pad_str(self.data_preparer_id, 128)
        buf[574:702] = self._pad_str(self.application_id, 128)
        buf[702:739] = self._pad_str("", 37)       # Copyright File ID
        buf[739:776] = self._pad_str("", 37)       # Abstract File ID
        buf[776:813] = self._pad_str("", 37)       # Bibliographic File ID
        buf[813:830] = self._iso_datetime_17(timestamp)    # Creation Date
        buf[830:847] = self._iso_datetime_17(timestamp)    # Modification Date
        buf[847:864] = b"0000000000000000\x00"             # Expiration Date (zeros)
        buf[864:881] = self._iso_datetime_17(timestamp)    # Effective Date
        buf[881] = 1                       # File Structure Version: 1
        buf[882] = 0                       # Unused: 0
        buf[883:1395] = b"\x00" * 512      # Application Use: zeros
        buf[1395:2048] = b"\x00" * 653     # Reserved: zeros

        return bytes(buf)

    def _build_brvd(self, boot_catalog_sector: int) -> bytes:
        """
        Construct the 2048-byte Boot Record Volume Descriptor (BRVD) at sector 17.
        """
        buf = bytearray(SECTOR_SIZE)
        buf[0] = ISO_VD_BOOT_RECORD
        buf[1:6] = ISO_STANDARD_ID
        buf[6] = 1                         # Version: 1
        # Boot System Identifier: "EL TORITO SPECIFICATION" padded with zeros to 32 bytes
        buf[7:39] = EL_TORITO_SYS_ID.ljust(32, b"\x00")
        buf[39:71] = b"\x00" * 32          # Unused: zeros
        buf[71:75] = struct.pack("<I", boot_catalog_sector)  # Pointer to Boot Catalog
        buf[75:2048] = b"\x00" * 1973      # Unused: zeros
        return bytes(buf)

    def _build_terminator(self) -> bytes:
        """
        Construct the 2048-byte Volume Descriptor Set Terminator.
        """
        buf = bytearray(SECTOR_SIZE)
        buf[0] = ISO_VD_SET_TERMINATOR
        buf[1:6] = ISO_STANDARD_ID
        buf[6] = 1                         # Version: 1
        buf[7:2048] = b"\x00" * 2041       # Zeros
        return bytes(buf)

    def _build_path_table_le(
        self,
        nodes: Optional[List[Any]] = None,
    ) -> bytes:
        """
        Construct the Type L (Little-Endian) Path Table.
        """
        if nodes is None:
            nodes = getattr(self, "_cached_path_nodes", [])
        out = bytearray()
        for node in nodes:
            # Entry: name_len(1), ext_attr(1), extent_sector(4 LE), parent_num(2 LE), name(N), pad(0-1)
            name_len = len(node.name_bytes)
            hdr = struct.pack("<BB I H", name_len, 0, node.sector, node.parent_num)
            pad = b"\x00" if (name_len % 2 != 0) else b""
            out.extend(hdr + node.name_bytes + pad)
        return bytes(out)

    def _build_path_table_be(
        self,
        nodes: Optional[List[Any]] = None,
    ) -> bytes:
        """
        Construct the Type M (Big-Endian) Path Table.
        """
        if nodes is None:
            nodes = getattr(self, "_cached_path_nodes", [])
        out = bytearray()
        for node in nodes:
            # Entry: name_len(1), ext_attr(1), extent_sector(4 BE), parent_num(2 BE), name(N), pad(0-1)
            name_len = len(node.name_bytes)
            hdr = struct.pack(">BB I H", name_len, 0, node.sector, node.parent_num)
            pad = b"\x00" if (name_len % 2 != 0) else b""
            out.extend(hdr + node.name_bytes + pad)
        return bytes(out)

    def _build_boot_catalog(
        self,
        bios_sector: int = 0,
        bios_sectors: int = 4,
        efi_sector: int = 0,
        efi_sectors: int = 0,
    ) -> bytes:
        """
        Construct the 2048-byte El Torito Boot Catalog.

        Contains:
          1. Validation Entry (32 bytes)
          2. Initial / Default Entry (BIOS boot payload) (32 bytes)
          3. Section Header Entry (UEFI boot section) (32 bytes, if EFI configured)
          4. Section Entry (UEFI efiboot payload) (32 bytes, if EFI configured)
        """
        catalog = bytearray(SECTOR_SIZE)

        # 1. Validation Entry (32 bytes at offset 0)
        val_entry = bytearray(32)
        val_entry[0] = EL_TORITO_HEADER_ID
        val_entry[1] = EL_TORITO_PLATFORM_X86
        # bytes 2-3: Reserved = 0
        id_str = self.publisher_id.encode("ascii", errors="replace")[:24].ljust(24, b"\x00")
        val_entry[4:28] = id_str
        # bytes 28-29: Checksum (initially 0)
        val_entry[30:32] = EL_TORITO_KEY_BYTES

        # Checksum calculation: sum of all 16 16-bit little-endian words sums to 0 mod 0x10000
        words = struct.unpack("<16H", val_entry)
        checksum = (-sum(words)) & 0xFFFF
        struct.pack_into("<H", val_entry, 28, checksum)
        catalog[0:32] = val_entry

        # 2. Initial / Default Entry (32 bytes at offset 32)
        def_entry = bytearray(32)
        if bios_sector > 0:
            def_entry[0] = EL_TORITO_BOOTABLE
            def_entry[1] = EL_TORITO_MEDIA_NO_EMULATION
            struct.pack_into("<H", def_entry, 2, 0x0000)  # Load segment 0x0000
            def_entry[4] = 0x00                          # System type
            def_entry[5] = 0x00                          # Unused
            struct.pack_into("<H", def_entry, 6, min(0xFFFF, max(1, bios_sectors)))
            struct.pack_into("<I", def_entry, 8, bios_sector)
        else:
            def_entry[0] = EL_TORITO_NOT_BOOTABLE
        catalog[32:64] = def_entry

        # 3. Additional Section Header + Entry (UEFI payload)
        offset = 64
        if efi_sector > 0:
            sec_hdr = bytearray(32)
            sec_hdr[0] = EL_TORITO_SECTION_HEADER_LAST
            sec_hdr[1] = EL_TORITO_PLATFORM_EFI
            struct.pack_into("<H", sec_hdr, 2, 1)        # 1 section entry follows
            sec_hdr[4:32] = b"EFI System Partition".ljust(28, b"\x00")
            catalog[offset:offset + 32] = sec_hdr
            offset += 32

            sec_entry = bytearray(32)
            sec_entry[0] = EL_TORITO_BOOTABLE
            sec_entry[1] = EL_TORITO_MEDIA_NO_EMULATION
            struct.pack_into("<H", sec_entry, 2, 0x0000) # Load segment
            sec_entry[4] = 0x00                          # System type
            sec_entry[5] = 0x00                          # Unused
            struct.pack_into("<H", sec_entry, 6, min(0xFFFF, max(1, efi_sectors)))
            struct.pack_into("<I", sec_entry, 8, efi_sector)
            catalog[offset:offset + 32] = sec_entry
            offset += 32

        return bytes(catalog)

    def _build_protective_mbr(self, total_sectors: int) -> bytes:
        """
        Construct a 512-byte Protective MBR for isohybrid booting at sector 0.

        Parameters
        ----------
        total_sectors : int
            Total size of the image in sectors.
        """
        mbr = bytearray(LBA_SIZE)
        # bytes 0-445: Bootstrap code (zeros)
        # bytes 446-461: Partition Entry 1
        lba_size = min(0xFFFFFFFF, max(0, total_sectors - 1))
        mbr[446] = 0x00                                  # Boot indicator: non-active
        mbr[447:450] = bytes([0x00, 0x02, 0x00])         # CHS first: 00 02 00
        mbr[450] = 0xEE                                  # Partition type: 0xEE (GPT Protective)
        mbr[451:454] = bytes([0xFF, 0xFF, 0xFF])         # CHS last: FF FF FF
        struct.pack_into("<I", mbr, 454, 1)              # LBA first: 1
        struct.pack_into("<I", mbr, 458, lba_size)       # LBA size: total_sectors - 1
        # bytes 462-509: Partition Entries 2-4 (zeros)
        mbr[510] = 0x55
        mbr[511] = 0xAA
        return bytes(mbr)

    def _build_gpt(
        self,
        total_sectors: int,
        efi_start_sector: int,
        efi_size_sectors: int,
    ) -> bytes:
        """
        Construct Primary GPT structures: Header (512 B) + Partition Entries Array (16384 B).
        Total returned size: 16,896 bytes (LBAs 1 to 33).

        Parameters
        ----------
        total_sectors : int
            Total image size in sectors.
        efi_start_sector : int
            Starting sector of efiboot.img.
        efi_size_sectors : int
            Size of efiboot.img in sectors.
        """
        # 1. Build 128 Partition Entries (128 * 128 = 16,384 bytes)
        entries_array = bytearray(GPT_PARTITION_ARRAY_SIZE)
        if efi_start_sector > 0 and efi_size_sectors > 0:
            entry0 = bytearray(GPT_PARTITION_ENTRY_SIZE)
            entry0[0:16] = GPT_ESP_GUID_BYTES
            part_guid = uuid.uuid5(uuid.NAMESPACE_DNS, f"{self.volume_id}.partition.efi")
            entry0[16:32] = part_guid.bytes_le
            struct.pack_into("<Q", entry0, 32, efi_start_sector)
            end_lba = efi_start_sector + efi_size_sectors - 1
            struct.pack_into("<Q", entry0, 40, end_lba)
            struct.pack_into("<Q", entry0, 48, 0)        # Attributes: 0
            name_bytes = "EFI System Partition".encode("utf-16le")[:72].ljust(72, b"\x00")
            entry0[56:128] = name_bytes
            entries_array[0:128] = entry0

        entries_crc = zlib.crc32(entries_array) & 0xFFFFFFFF

        # 2. Build GPT Header (512 bytes)
        hdr = bytearray(LBA_SIZE)
        hdr[0:8] = GPT_SIGNATURE
        struct.pack_into("<I", hdr, 8, GPT_REVISION)
        struct.pack_into("<I", hdr, 12, GPT_HEADER_SIZE)
        struct.pack_into("<I", hdr, 16, 0)               # Zeroed for CRC calculation
        struct.pack_into("<I", hdr, 20, 0)               # Reserved: 0
        struct.pack_into("<Q", hdr, 24, 1)               # My LBA: 1
        alternate_lba = max(1, total_sectors - 1)
        struct.pack_into("<Q", hdr, 32, alternate_lba)   # Alternate LBA
        struct.pack_into("<Q", hdr, 40, 34)              # First usable LBA: 34
        last_usable = max(0, total_sectors - 34)
        struct.pack_into("<Q", hdr, 48, last_usable)     # Last usable LBA
        disk_guid = uuid.uuid5(uuid.NAMESPACE_DNS, f"{self.volume_id}.disk")
        hdr[56:72] = disk_guid.bytes_le
        struct.pack_into("<Q", hdr, 72, 2)               # Partition entries start LBA: 2
        struct.pack_into("<I", hdr, 80, GPT_NUM_PARTITION_ENTRIES)
        struct.pack_into("<I", hdr, 84, GPT_PARTITION_ENTRY_SIZE)
        struct.pack_into("<I", hdr, 88, entries_crc)

        # Header CRC calculation over the first 92 bytes
        hdr_crc = zlib.crc32(hdr[0:92]) & 0xFFFFFFFF
        struct.pack_into("<I", hdr, 16, hdr_crc)

        return bytes(hdr + entries_array)

    def _build_backup_gpt(
        self,
        total_sectors: int,
        efi_start_sector: int,
        efi_size_sectors: int,
    ) -> Tuple[bytes, bytes]:
        """
        Construct the Backup GPT Partition Entries array (16,384 bytes) and Backup GPT Header (512 bytes).
        """
        # Rebuild partition entries
        entries_array = bytearray(GPT_PARTITION_ARRAY_SIZE)
        if efi_start_sector > 0 and efi_size_sectors > 0:
            entry0 = bytearray(GPT_PARTITION_ENTRY_SIZE)
            entry0[0:16] = GPT_ESP_GUID_BYTES
            part_guid = uuid.uuid5(uuid.NAMESPACE_DNS, f"{self.volume_id}.partition.efi")
            entry0[16:32] = part_guid.bytes_le
            struct.pack_into("<Q", entry0, 32, efi_start_sector)
            end_lba = efi_start_sector + efi_size_sectors - 1
            struct.pack_into("<Q", entry0, 40, end_lba)
            struct.pack_into("<Q", entry0, 48, 0)
            name_bytes = "EFI System Partition".encode("utf-16le")[:72].ljust(72, b"\x00")
            entry0[56:128] = name_bytes
            entries_array[0:128] = entry0

        entries_crc = zlib.crc32(entries_array) & 0xFFFFFFFF

        hdr = bytearray(LBA_SIZE)
        hdr[0:8] = GPT_SIGNATURE
        struct.pack_into("<I", hdr, 8, GPT_REVISION)
        struct.pack_into("<I", hdr, 12, GPT_HEADER_SIZE)
        struct.pack_into("<I", hdr, 16, 0)
        struct.pack_into("<I", hdr, 20, 0)
        my_lba = max(1, total_sectors - 1)
        struct.pack_into("<Q", hdr, 24, my_lba)          # Backup My LBA
        struct.pack_into("<Q", hdr, 32, 1)               # Primary Alternate LBA = 1
        struct.pack_into("<Q", hdr, 40, 34)              # First usable LBA: 34
        last_usable = max(0, total_sectors - 34)
        struct.pack_into("<Q", hdr, 48, last_usable)
        disk_guid = uuid.uuid5(uuid.NAMESPACE_DNS, f"{self.volume_id}.disk")
        hdr[56:72] = disk_guid.bytes_le
        part_start_lba = max(2, total_sectors - 33)
        struct.pack_into("<Q", hdr, 72, part_start_lba)  # Partition entries LBA
        struct.pack_into("<I", hdr, 80, GPT_NUM_PARTITION_ENTRIES)
        struct.pack_into("<I", hdr, 84, GPT_PARTITION_ENTRY_SIZE)
        struct.pack_into("<I", hdr, 88, entries_crc)

        hdr_crc = zlib.crc32(hdr[0:92]) & 0xFFFFFFFF
        struct.pack_into("<I", hdr, 16, hdr_crc)

        return bytes(entries_array), bytes(hdr)

    # ------------------------------------------------------------------
    # Directory Packing Helper
    # ------------------------------------------------------------------

    def _pack_dir_records(self, records: List[bytes]) -> bytes:
        """
        Pack directory records into 2048-byte sectors according to ISO 9660 rules:
        Records shall not cross logical sector boundaries. Unused bytes at the
        end of each sector are padded with NUL bytes.
        """
        if not records:
            return b"\x00" * SECTOR_SIZE

        sectors: List[bytearray] = [bytearray(SECTOR_SIZE)]
        cur_offset = 0

        for rec in records:
            rlen = len(rec)
            if cur_offset + rlen > SECTOR_SIZE:
                sectors.append(bytearray(SECTOR_SIZE))
                cur_offset = 0
            sectors[-1][cur_offset:cur_offset + rlen] = rec
            cur_offset += rlen

        return b"".join(sectors)

    # ------------------------------------------------------------------
    # Assembly Pipeline: build()
    # ------------------------------------------------------------------

    def build(self) -> bytes:
        """
        Assemble the complete bootable hybrid ISO image.

        Returns
        -------
        bytes
            Sector-aligned ISO9660 + El Torito + GPT disk image.
        """
        has_boot = bool(self._bios_boot_image or self._efi_boot_image)

        # 1. Normalise directories & collect files
        all_dirs: Set[str] = {"/"}
        for d in self._directories:
            all_dirs.add(self._normalise_path(d))
        for f in self._files:
            parent = str(PurePosixPath(self._normalise_path(f)).parent)
            all_dirs.add(self._normalise_path(parent))

        # BFS order of directories: root is 1, depth-sorted, then path-sorted
        sorted_dirs = sorted(
            all_dirs,
            key=lambda p: (0 if p == "/" else len(p.strip("/").split("/")), p)
        )

        dir_to_idx: Dict[str, int] = {p: i + 1 for i, p in enumerate(sorted_dirs)}

        # Build path table node list
        path_nodes: List[_PathDirNode] = []
        for p in sorted_dirs:
            idx = dir_to_idx[p]
            if p == "/":
                parent_idx = 1
                name_bytes = b"\x01"
                depth = 0
            else:
                parent_path = str(PurePosixPath(p).parent)
                parent_idx = dir_to_idx.get(parent_path, 1)
                basename = PurePosixPath(p).name
                name_bytes = self._iso_filename(basename, is_dir=True)
                depth = len(p.strip("/").split("/"))

            path_nodes.append(_PathDirNode(
                path=p,
                dir_num=idx,
                parent_num=parent_idx,
                name_bytes=name_bytes,
                depth=depth,
            ))

        self._cached_path_nodes = path_nodes

        # Calculate exact Path Table size
        path_table_raw_size = 0
        for node in path_nodes:
            n = len(node.name_bytes)
            # 8 bytes header + name + padding
            entry_sz = 8 + n + (1 if n % 2 != 0 else 0)
            path_table_raw_size += entry_sz

        path_table_sectors = max(1, (path_table_raw_size + SECTOR_SIZE - 1) // SECTOR_SIZE)

        # Determine children for each directory
        dir_subdirs: Dict[str, List[str]] = collections.defaultdict(list)
        for p in sorted_dirs:
            if p == "/":
                continue
            parent = str(PurePosixPath(p).parent)
            dir_subdirs[parent].append(p)

        dir_files: Dict[str, List[str]] = collections.defaultdict(list)
        for f in self._files:
            parent = str(PurePosixPath(f).parent)
            dir_files[parent].append(f)

        # Pre-compute directory record lengths to determine directory extent sectors
        dir_sector_counts: Dict[str, int] = {}
        for p in sorted_dirs:
            dummy_records: List[bytes] = []
            # . record (34 bytes)
            dummy_records.append(self._build_directory_record(".", 0, 0, is_dir=True))
            # .. record (34 bytes)
            dummy_records.append(self._build_directory_record("..", 0, 0, is_dir=True))

            child_entries: List[Tuple[bytes, bytes]] = []
            for subdir in sorted(dir_subdirs[p]):
                s_name = PurePosixPath(subdir).name
                rec = self._build_directory_record(s_name, 0, 0, is_dir=True)
                child_entries.append((self._iso_filename(s_name, is_dir=True), rec))

            for fil in sorted(dir_files[p]):
                f_name = PurePosixPath(fil).name
                f_data = self._files[fil]
                rec = self._build_directory_record(f_name, 0, len(f_data), is_dir=False)
                child_entries.append((self._iso_filename(f_name, is_dir=False), rec))

            child_entries.sort(key=lambda item: item[0])
            for _, rec in child_entries:
                dummy_records.append(rec)

            packed_dummy = self._pack_dir_records(dummy_records)
            dir_sector_counts[p] = len(packed_dummy) // SECTOR_SIZE

        # ------------------------------------------------------------------
        # Assign Sector Positions
        # ------------------------------------------------------------------
        # Layout plan:
        # Sectors 0-15: System area
        # Sector 16: PVD
        # Sector 17: BRVD (if has_boot) or Terminator
        # Sector 18: Terminator (if has_boot)
        # Next: Type L Path Table (path_table_sectors)
        # Next: Type M Path Table (path_table_sectors)
        # Next: Directory Extents
        # Next: File Data Extents
        # Next: Boot Catalog (1 sector, if has_boot)
        # Next: BIOS Boot Image (if present)
        # Next: EFI Boot Image (if present)
        # Next: Backup GPT padding & structures (9 sectors)

        cur_sector = 16  # PVD
        pvd_sector = cur_sector
        cur_sector += 1

        if has_boot:
            brvd_sector = cur_sector
            cur_sector += 1
            terminator_sector = cur_sector
            cur_sector += 1
        else:
            brvd_sector = 0
            terminator_sector = cur_sector
            cur_sector += 1

        path_table_le_sector = cur_sector
        cur_sector += path_table_sectors

        path_table_be_sector = cur_sector
        cur_sector += path_table_sectors

        # Directory extents
        dir_extent_sectors: Dict[str, int] = {}
        for p in sorted_dirs:
            dir_extent_sectors[p] = cur_sector
            for node in path_nodes:
                if node.path == p:
                    node.sector = cur_sector
                    node.size_bytes = dir_sector_counts[p] * SECTOR_SIZE
                    break
            cur_sector += dir_sector_counts[p]

        # File data extents
        file_extent_sectors: Dict[str, int] = {}
        sorted_files = sorted(self._files.keys())
        for f in sorted_files:
            fdata = self._files[f]
            flen = len(fdata)
            f_sectors = max(1, (flen + SECTOR_SIZE - 1) // SECTOR_SIZE) if flen > 0 else 0
            file_extent_sectors[f] = cur_sector
            cur_sector += f_sectors

        # Boot payloads
        boot_cat_sector = 0
        bios_sec = 0
        bios_sec_count = 0
        efi_sec = 0
        efi_sec_count = 0

        if has_boot:
            boot_cat_sector = cur_sector
            cur_sector += 1

            if self._bios_boot_image:
                bios_sec = cur_sector
                bios_sec_count = max(1, (len(self._bios_boot_image) + SECTOR_SIZE - 1) // SECTOR_SIZE)
                cur_sector += bios_sec_count

            if self._efi_boot_image:
                efi_sec = cur_sector
                efi_sec_count = max(1, (len(self._efi_boot_image) + SECTOR_SIZE - 1) // SECTOR_SIZE)
                cur_sector += efi_sec_count

        # ISO run-out and backup GPT allocation
        # GPT specifications reserve 33 LBAs (32 partition table + 1 header) = 16,896 B at end
        # We allocate 9 sectors (18,432 B = 36 LBAs) for backup GPT and alignment.
        backup_gpt_sectors = 9
        # Ensure total sectors >= 35 so last_usable_lba = total_sectors - 34 >= 1
        min_total_sectors = 35 + backup_gpt_sectors
        if cur_sector + backup_gpt_sectors < min_total_sectors:
            cur_sector = min_total_sectors - backup_gpt_sectors

        total_sectors = cur_sector + backup_gpt_sectors

        # ------------------------------------------------------------------
        # Buffer Allocation & Direct Assembly
        # ------------------------------------------------------------------
        total_image_bytes = total_sectors * SECTOR_SIZE
        iso_buffer = bytearray(total_image_bytes)

        # 2. Build Root Directory Record for PVD
        root_extent = dir_extent_sectors["/"]
        root_data_len = dir_sector_counts["/"] * SECTOR_SIZE
        root_dir_record = self._build_directory_record(
            ".",
            root_extent,
            root_data_len,
            is_dir=True,
            timestamp=self._creation_time,
        )

        # 3. Write PVD (sector 16)
        pvd_bytes = self._build_pvd(
            total_sectors=total_sectors,
            path_table_size=path_table_raw_size,
            path_table_le_sector=path_table_le_sector,
            path_table_be_sector=path_table_be_sector,
            root_dir_record=root_dir_record,
            timestamp=self._creation_time,
        )
        iso_buffer[pvd_sector * SECTOR_SIZE:(pvd_sector + 1) * SECTOR_SIZE] = pvd_bytes

        # 4. Write BRVD (sector 17, if bootable)
        if has_boot:
            brvd_bytes = self._build_brvd(boot_cat_sector)
            iso_buffer[brvd_sector * SECTOR_SIZE:(brvd_sector + 1) * SECTOR_SIZE] = brvd_bytes

        # 5. Write Terminator
        terminator_bytes = self._build_terminator()
        iso_buffer[terminator_sector * SECTOR_SIZE:(terminator_sector + 1) * SECTOR_SIZE] = terminator_bytes

        # 6. Write Path Tables
        pt_le = self._build_path_table_le(path_nodes)
        iso_buffer[path_table_le_sector * SECTOR_SIZE:path_table_le_sector * SECTOR_SIZE + len(pt_le)] = pt_le

        pt_be = self._build_path_table_be(path_nodes)
        iso_buffer[path_table_be_sector * SECTOR_SIZE:path_table_be_sector * SECTOR_SIZE + len(pt_be)] = pt_be

        # 7. Write Directory Extents
        for p in sorted_dirs:
            records: List[bytes] = []
            dir_sec = dir_extent_sectors[p]
            dir_sz = dir_sector_counts[p] * SECTOR_SIZE

            # Parent resolution
            if p == "/":
                parent_sec = dir_extent_sectors["/"]
                parent_sz = dir_sector_counts["/"] * SECTOR_SIZE
            else:
                parent_path = str(PurePosixPath(p).parent)
                parent_sec = dir_extent_sectors[parent_path]
                parent_sz = dir_sector_counts[parent_path] * SECTOR_SIZE

            # . record
            records.append(self._build_directory_record(
                ".",
                dir_sec,
                dir_sz,
                is_dir=True,
                timestamp=self._dir_mtimes.get(p, self._creation_time),
            ))
            # .. record
            records.append(self._build_directory_record(
                "..",
                parent_sec,
                parent_sz,
                is_dir=True,
                timestamp=self._dir_mtimes.get(p, self._creation_time),
            ))

            child_records: List[Tuple[bytes, bytes]] = []
            for subdir in sorted(dir_subdirs[p]):
                s_name = PurePosixPath(subdir).name
                s_sec = dir_extent_sectors[subdir]
                s_sz = dir_sector_counts[subdir] * SECTOR_SIZE
                s_mtime = self._dir_mtimes.get(subdir, self._creation_time)
                rec = self._build_directory_record(s_name, s_sec, s_sz, is_dir=True, timestamp=s_mtime)
                child_records.append((self._iso_filename(s_name, is_dir=True), rec))

            for fil in sorted(dir_files[p]):
                f_name = PurePosixPath(fil).name
                f_data = self._files[fil]
                f_sec = file_extent_sectors[fil]
                f_mtime = self._file_mtimes.get(fil, self._creation_time)
                rec = self._build_directory_record(f_name, f_sec, len(f_data), is_dir=False, timestamp=f_mtime)
                child_records.append((self._iso_filename(f_name, is_dir=False), rec))

            child_records.sort(key=lambda item: item[0])
            for _, rec in child_records:
                records.append(rec)

            packed_dir = self._pack_dir_records(records)
            iso_buffer[dir_sec * SECTOR_SIZE:dir_sec * SECTOR_SIZE + len(packed_dir)] = packed_dir

        # 8. Write File Data
        for f in sorted_files:
            fdata = self._files[f]
            f_sec = file_extent_sectors[f]
            iso_buffer[f_sec * SECTOR_SIZE:f_sec * SECTOR_SIZE + len(fdata)] = fdata

        # 9. Write Boot Catalog & Boot Images
        if has_boot:
            # 512-byte sector count for El Torito
            bios_512_count = (len(self._bios_boot_image) + 511) // 512 if self._bios_boot_image else 4
            efi_512_count = (len(self._efi_boot_image) + 511) // 512 if self._efi_boot_image else 0

            boot_cat_bytes = self._build_boot_catalog(
                bios_sector=bios_sec,
                bios_sectors=bios_512_count,
                efi_sector=efi_sec,
                efi_sectors=efi_512_count,
            )
            iso_buffer[boot_cat_sector * SECTOR_SIZE:(boot_cat_sector + 1) * SECTOR_SIZE] = boot_cat_bytes

            if self._bios_boot_image:
                iso_buffer[bios_sec * SECTOR_SIZE:bios_sec * SECTOR_SIZE + len(self._bios_boot_image)] = self._bios_boot_image

            if self._efi_boot_image:
                iso_buffer[efi_sec * SECTOR_SIZE:efi_sec * SECTOR_SIZE + len(self._efi_boot_image)] = self._efi_boot_image

        # 10. Overlay Isohybrid Structures: Protective MBR at Sector 0 (LBA 0)
        mbr_bytes = self._build_protective_mbr(total_sectors)
        iso_buffer[0:LBA_SIZE] = mbr_bytes

        # 11. Overlay Primary GPT at LBA 1-33 (bytes 512-17407)
        gpt_primary_bytes = self._build_gpt(
            total_sectors=total_sectors,
            efi_start_sector=efi_sec,
            efi_size_sectors=efi_sec_count,
        )
        iso_buffer[LBA_SIZE:LBA_SIZE + len(gpt_primary_bytes)] = gpt_primary_bytes

        # 12. Write Backup GPT at image end
        backup_entries, backup_hdr = self._build_backup_gpt(
            total_sectors=total_sectors,
            efi_start_sector=efi_sec,
            efi_size_sectors=efi_sec_count,
        )
        # Backup entries placed at LBA total_sectors - 33
        backup_entries_offset = total_image_bytes - LBA_SIZE - GPT_PARTITION_ARRAY_SIZE
        iso_buffer[backup_entries_offset:backup_entries_offset + GPT_PARTITION_ARRAY_SIZE] = backup_entries

        # Backup header placed at LBA total_sectors - 1
        backup_hdr_offset = total_image_bytes - LBA_SIZE
        iso_buffer[backup_hdr_offset:backup_hdr_offset + LBA_SIZE] = backup_hdr

        return bytes(iso_buffer)


