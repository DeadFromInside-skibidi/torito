# Constants & On-Disk Layout Specifications
# ---------------------------------------------------------------------------

SECTOR_SIZE: int = 2048
LBA_SIZE: int = 512

# Standard ISO9660 volume descriptor identifiers
ISO_STANDARD_ID: bytes = b"CD001"
ISO_VD_BOOT_RECORD: int = 0
ISO_VD_PRIMARY: int = 1
ISO_VD_SUPPLEMENTARY: int = 2
ISO_VD_VOLUME_PARTITION: int = 3
ISO_VD_SET_TERMINATOR: int = 255

# El Torito constants
EL_TORITO_SYS_ID: bytes = b"EL TORITO SPECIFICATION"
EL_TORITO_BOOTABLE: int = 0x88
EL_TORITO_NOT_BOOTABLE: int = 0x00
EL_TORITO_MEDIA_NO_EMULATION: int = 0x00
EL_TORITO_PLATFORM_X86: int = 0x00
EL_TORITO_PLATFORM_EFI: int = 0xEF
EL_TORITO_HEADER_ID: int = 0x01
EL_TORITO_SECTION_HEADER_LAST: int = 0x91
EL_TORITO_KEY_BYTES: bytes = b"\x55\xAA"

# GPT Partition Type GUID for EFI System Partition (mixed-endian UUID format):
# C12A7328-F81F-11D2-BA4B-00A0C93EC93B
GPT_ESP_GUID_BYTES: bytes = bytes([
    0x28, 0x73, 0x2A, 0xC1,
    0x1F, 0xF8,
    0xD2, 0x11,
    0xBA, 0x4B,
    0x00, 0xA0, 0xC9, 0x3E, 0xC9, 0x3B,
])

