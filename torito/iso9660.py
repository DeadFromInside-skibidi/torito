"""
torito.iso9660 — Production-Grade Hybrid ISO9660 + El Torito + GPT Assembler
=============================================================================
Synthesises fully compliant ISO9660 filesystem images equipped with El Torito
boot records (BIOS and UEFI) and an isohybrid Protective MBR + GPT partition
table layout.

Images generated by this module are dual-bootable:
  - As optical media (CD/DVD) via standard ISO9660 + El Torito boot catalog.
  - As raw disk drives (USB flash drive / dd-target) via Protective MBR and
    GPT EFI System Partition (ESP) pointers to the embedded efiboot image.
"""

